const assert = require('node:assert/strict')
const { checks } = require('../filing-readiness-rules.js')
const values = checks({ selected: { order_count: 20, closed_days: 2, uncosted_items: 0, unknown_tax_count: 0, missing_evidence_count: 0 } }, { pending_count: 0 }, { drafts: 0 }, 1)
assert.equal(values.some(x => x.level === 'blocked'), true)
assert.equal(values.some(x => x.label === '売上と日次締め' && x.level === 'review'), true)
assert.equal(values.some(x => x.label === '商品原価・棚卸' && x.level === 'review'), true)
const missing = checks({ selected: { order_count: 0, closed_days: 0, unknown_tax_count: 3, missing_evidence_count: 2 } }, null, null, 2)
assert.equal(missing.find(x => x.label === '売上の記録').level, 'unknown')
assert.equal(missing.find(x => x.label === '経費の税区分・証憑').level, 'action')
assert.equal(missing.find(x => x.label === 'レシート確認').level, 'unknown')
assert.equal(missing.every(x => x.level !== 'ready'), true)
console.log('PASS filing readiness does not infer completion from incomplete data')
