import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync(new URL('../customer-promotions.js',import.meta.url),'utf8'),context);
const api=context.window.CustomerPromotions;
const drink=(id,extra={})=>({id,category_id:5,name:'お酒',price_type:'happy_hour',sale_status:'available',regular_price:600,price:200,price_rule_end_time:'22:00:00',...extra});
const data={categories:[{id:5,name:'アルコール'}],products:[drink(31),drink(29),drink(30),drink(40,{sale_status:'sold_out'}),drink(41,{category_id:6}),drink(42,{price:600})]};
assert.deepEqual(Array.from(api.happyDrinks(data),p=>p.id),[29,30,31]);
for(const ordering of [{enabled:false},{is_open:false}]) assert.equal(api.happyDrinks({...data,ordering}).length,0);
assert.equal(api.renderHappy({...data,products:[]},String,String),'');
assert.deepEqual(Array.from(api.recommendations({products:[{id:20},{id:5,sale_status:'sold_out'},{id:6},{id:16},{id:99}]}),p=>p.id),[5,6,16,20]);
assert.equal(api.recommendations({products:[{id:5}]}).length,1);
const html=api.renderHappy(data,String,n=>'¥'+n);
assert.ok(html.includes('22:00まで'));
assert.ok(html.includes('¥400お得'));
assert.ok(html.includes('カートに追加'));
assert.ok(!html.includes('data-happy-product="40"'));
console.log('Customer promotions behavior checks passed');
