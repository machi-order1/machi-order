import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html = await fs.readFile(new URL('../index.html', import.meta.url), 'utf8');
const c = { window: {}, alert: message => { c.error = message; }, drawProduct() {}, saveCart() {}, updateCart() {}, showCart() { c.editingItem = null; }, $: () => ({}) };
vm.createContext(c);
vm.runInContext(await fs.readFile(new URL('../customer-options.js', import.meta.url), 'utf8'), c);
c.CustomerOptions = c.window.CustomerOptions;
vm.runInContext(html.slice(html.indexOf('    function editCartItem('), html.indexOf('    function drawProduct()')), c);
vm.runInContext(html.match(/    function closeModal\(\) \{[^\n]+/)[0], c);
const groups = [{ id: 1, name: '麺量', required: true, min_select: 1, max_select: 1, options: [{ id: 1, name: '普通', price_delta: 0 }, { id: 2, name: 'W玉', price_delta: 200 }, { id: 3, name: '旧選択', available: false }] }];
c.data = { products: [{ id: 5, name: '博多油そば', price: 1000, sale_status: 'available' }] };
c.productGroups = () => groups;
c.optionDetails = ids => groups.flatMap(g => g.options).filter(o => ids.includes(o.id));
c.optionDelta = () => c.optionDetails(Object.values(c.selected).flat()).reduce((sum, o) => sum + Number(o.price_delta || 0), 0);
const original = { product_id: 5, name: '博多油そば', quantity: 2, price: 1000, option_ids: [1], option_names: ['普通'] };
const other = { ...original, quantity: 1, option_ids: [2], price: 1200 };
c.cart = [original, other];
c.editCartItem(0);
assert.equal(c.quantity, 1);
assert.deepEqual(Array.from(c.selected[1]), [1]);
c.selected[1] = [2];
assert.deepEqual(original.option_ids, [1], 'draft must not mutate cart');
c.saveEditedItem();
assert.equal(c.cart.length, 3);
assert.equal(c.cart[0].quantity, 1);
assert.equal(c.cart[1].price, 1200);
assert.equal(c.cart[2], other, 'other bowl untouched');
assert.equal(c.cart.reduce((sum, i) => sum + i.quantity * i.price, 0), 3400);
c.cart = [original]; c.editCartItem(0); c.selected[1] = [2]; c.quantity = 2; c.saveEditedItem();
assert.equal(c.cart.length, 1); assert.equal(c.cart[0].quantity, 2); assert.equal(c.cart[0].price, 1200);
c.cart = [original]; c.editCartItem(0); c.saveEditedItem();
assert.equal(c.cart.length, 1); assert.equal(c.cart[0].quantity, 2, 'unchanged partial edit must not duplicate');
c.cart = [original]; c.editCartItem(0); c.selected[1] = [2]; c.closeModal();
assert.equal(c.editingItem, null); assert.equal(c.cart[0], original, 'cancel leaves original cart');
c.editCartItem(0); c.selected[1] = []; c.saveEditedItem();
assert.match(c.error, /選んで/); assert.equal(c.cart[0], original);
assert.throws(() => c.editedCartLines([original], 0, { ...original, quantity: 3 }), /数量/);
c.cart = [{ ...original, option_ids: [3] }]; c.editCartItem(0);
assert.equal(c.editingItem.optionsChanged, true); assert.equal(c.selected[1].length, 0);
c.data.products[0].sale_status = 'sold_out'; c.error = ''; c.editCartItem(0); assert.match(c.error, /変更できません/);
console.log('PASS: restore choices; draft/cancel isolation; partial/all edits; recalculation; sibling preservation; no-op; bounds; required and unavailable choices.');
